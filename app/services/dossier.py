"""Cybercrime Dossier Builder.
Formats structured incident reports ready for National Cybercrime Portal (cybercrime.gov.in / 1930).
"""

import hashlib
import datetime
from typing import Dict, Any, Optional, List


def determine_bns_it_sections(violations: List[str], reasons: List[str]) -> List[str]:
    """Map detected scam vectors to relevant provisions of Indian Law (BNS and IT Act)."""
    sections = [
        "Section 66D, Information Technology Act, 2000 (Cheating by personation using computer resource)",
        "Section 318(4), Bharatiya Nyaya Sanhita, 2023 / Sec 420 IPC (Cheating and dishonestly inducing delivery of property)"
    ]

    all_text = " ".join(violations + reasons).lower()

    if any(k in all_text for k in ["impersonation", "police", "cbi", "customs", "court", "judge"]):
        sections.append("Section 204, Bharatiya Nyaya Sanhita, 2023 / Sec 170 IPC (Personating a public servant)")

    if any(k in all_text for k in ["arrest", "extortion", "security deposit", "clearance fee"]):
        sections.append("Section 308(2), Bharatiya Nyaya Sanhita, 2023 / Sec 384 IPC (Extortion)")

    if any(k in all_text for k in ["apk", "malware", "trojan", "sms"]):
        sections.append("Section 66, Information Technology Act, 2000 (Computer related offences & hacking)")
        sections.append("Section 43, Information Technology Act, 2000 (Penalty for damage to computer systems)")

    return sections


def build_cybercrime_dossier(result: Dict[str, Any], raw_input: Optional[str] = None) -> Dict[str, Any]:
    """
    Generate a pre-filled 1930 / cybercrime.gov.in formal complaint dossier.
    """
    now = datetime.datetime.now(datetime.timezone.utc)
    timestamp_str = now.strftime("%Y-%m-%d %H:%M:%S UTC")

    # Hash input artifact for evidentiary chain of custody
    full_sha256 = hashlib.sha256((raw_input or "").encode("utf-8")).hexdigest()
    payload_hash = full_sha256[:16]
    dossier_id = f"KAVACH-{now.strftime('%Y%m%d')}-{payload_hash.upper()}"

    # Extract suspect identifiers
    suspect_vpas = []
    if result.get("vpa") and result["vpa"] != "N/A":
        suspect_vpas.append(result["vpa"])

    suspect_urls = result.get("extracted_urls", [])
    suspect_phones = result.get("extracted_contacts", [])
    fabricated_cnr = result.get("cnr_number")

    # Statutory sections
    violations = result.get("detected_violations", [])
    reasons = result.get("reasons", [])
    statutory_sections = determine_bns_it_sections(violations, reasons)

    # Formal FIR narrative ready for copy-pasting
    narrative_lines = [
        f"--- NATIONAL CYBERCRIME REPORTING PORTAL (1930) - FIR NARRATIVE TEMPLATE ---",
        f"RESPECTED SIR/MADAM,",
        f"",
        f"I wish to report an active cyber fraud and financial extortion attempt intercepted on {timestamp_str}.",
        f"The suspect approached using the following modus operandi: {result.get('summary', 'Fraudulent extortion attempt')}.",
        f"",
        f"INCIDENT EVIDENCE & IDENTIFIERS:",
    ]

    if suspect_vpas:
        narrative_lines.append(f"• Suspect Beneficiary UPI VPA: {', '.join(suspect_vpas)}")
    if suspect_urls:
        narrative_lines.append(f"• Phishing / Malicious URLs: {', '.join(suspect_urls)}")
    if suspect_phones:
        narrative_lines.append(f"• Suspect Contact Number(s): {', '.join(suspect_phones)}")
    if fabricated_cnr:
        narrative_lines.append(f"• Forged Court CNR Number: {fabricated_cnr}")

    narrative_lines.extend([
        f"",
        f"FORENSIC VIOLATIONS IDENTIFIED:",
    ])
    for r in reasons[:4]:
        narrative_lines.append(f"• {r}")

    narrative_lines.extend([
        f"",
        f"PRAYER:",
        f"I request your kind authority to immediately lodge a formal complaint under the Information Technology Act and BNS, "
        f"freeze the aforementioned suspect accounts/VPAs through the 1930 NCRP network, and block the associated telecommunication lines.",
        f"",
        f"EVIDENTIARY HASH (SHA-256): {full_sha256}",
        f"GENERATED BY: KavachAI Universal Scam Verification Engine"
    ])

    fir_narrative = "\n".join(narrative_lines)

    # Section 63 BSA / 65B Evidence Certificate Text
    bsa_certificate = (
        f"CERTIFICATE UNDER SECTION 63 OF THE BHARATIYA SAKSHYA ADHINIYAM (BSA), 2023 / "
        f"SECTION 65B OF THE INDIAN EVIDENCE ACT, 1872\n\n"
        f"I hereby certify that this electronic dossier (ID: {dossier_id}) was produced automatically by the KavachAI "
        f"computer system during its normal operations on {timestamp_str}.\n"
        f"1. The digital input artifact was ingested directly without manual alteration.\n"
        f"2. Cryptographic Integrity Hash: SHA-256: {full_sha256}\n"
        f"3. System state, forensic rule engines, and timestamps operated in normal course without unauthorized modification.\n"
        f"This document constitutes admissible primary electronic evidence for registration of FIR under Section 173 BNSS."
    )

    from app.core.config import BANK_FREEZE_DIRECTORY

    return {
        "dossier_id": dossier_id,
        "generated_at": timestamp_str,
        "helpline": "1930",
        "portal_url": "https://cybercrime.gov.in",
        "verdict": result.get("verdict", "SUSPICIOUS"),
        "confidence_score": result.get("confidence", 0.0),
        "threat_category": violations[0] if violations else "CYBER_FRAUD_ATTEMPT",
        "incident_category": "Identity Theft & Extortion" if any("impersonat" in str(r).lower() or "extort" in str(r).lower() for r in reasons) else (violations[0] if violations else "CYBER_FRAUD_ATTEMPT"),
        "sha256_evidence_hash": full_sha256,
        "suspect_identifiers": {
            "vpa_accounts": suspect_vpas,
            "phishing_domains": suspect_urls,
            "contact_numbers": suspect_phones,
            "fabricated_cnr": fabricated_cnr,
        },
        "suspect_indicators": {
            "upi_vpas": suspect_vpas,
            "phishing_domains": suspect_urls,
            "contact_numbers": suspect_phones,
            "fabricated_cnr": fabricated_cnr,
        },
        "applicable_legal_sections": statutory_sections,
        "statutory_violations": statutory_sections,
        "fir_narrative": fir_narrative,
        "fir_narrative_template": fir_narrative,
        "bsa_section_63_certificate": bsa_certificate,
        "golden_hour_bank_freeze": {
            "ncrp_helpline": "1930",
            "emergency_dial_url": "tel:1930",
            "golden_hour_notice": "Transfer recall success is highest within the first 60 to 120 minutes of transaction before mule accounts can withdraw funds.",
            "banks": BANK_FREEZE_DIRECTORY,
        },
        "emergency_checklist": [
            "1. GOLDEN HOUR ACTION: If money was transferred, immediately dial 1930 or use the 1-Click Bank Freeze actions below.",
            "2. DO NOT transfer any funds or enter your UPI PIN.",
            "3. Submit this pre-filled dossier at https://cybercrime.gov.in.",
            "4. Download and print the Section 63 BSA PDF Incident Summary for your local Cyber Cell police station.",
            "5. If an APK was downloaded, disconnect WiFi/data immediately and uninstall the application in Safe Mode."
        ]
    }
